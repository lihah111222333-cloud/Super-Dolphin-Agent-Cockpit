// Package reverse provides a Unicode-aware string reversal helper.
package reverse

// String returns s reversed rune-wise from left to right.
func String(s string) string {
	runes := []rune(s)
	for i, j := 0, len(runes)-1; i < j; i, j = i+1, j-1 {
		runes[i], runes[j] = runes[j], runes[i]
	}
	return string(runes)
}
