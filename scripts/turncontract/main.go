package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

type document struct {
	ID    string `json:"$id"`
	Title string `json:"title"`
}

type renderedSchema struct {
	name       string
	raw        []byte
	references []string
}

// main 从唯一 JSON schema 真值生成 Go 与 JS 派生 manifest，或校验它们未漂移。
func main() {
	verify := flag.Bool("verify", false, "verify generated contract manifests are current")
	flag.Parse()

	root, err := repoRoot()
	if err != nil {
		fail(err)
	}
	schemas, err := loadSchemas(filepath.Join(root, "internal", "dto", "turn", "schema"))
	if err != nil {
		fail(err)
	}
	goOutput := renderGo(schemas)
	jsOutput, err := renderJS(schemas)
	if err != nil {
		fail(err)
	}
	targets := []struct {
		path string
		data []byte
	}{
		{filepath.Join(root, "internal", "dto", "turn", "turn_contract_schemas_generated.go"), goOutput},
		{filepath.Join(root, "frontend-app", "src", "shared", "contracts", "turnContracts.generated.js"), jsOutput},
	}
	for _, target := range targets {
		if *verify {
			actual, readErr := os.ReadFile(target.path)
			if readErr != nil || !bytes.Equal(actual, target.data) {
				fail(fmt.Errorf("generated contract manifest is stale: %s; run go generate ./internal/dto/turn", target.path))
			}
			continue
		}
		if err := os.MkdirAll(filepath.Dir(target.path), 0o755); err != nil {
			fail(fmt.Errorf("create generated output directory: %w", err))
		}
		if err := os.WriteFile(target.path, target.data, 0o644); err != nil {
			fail(fmt.Errorf("write generated contract manifest: %w", err))
		}
	}
}

func repoRoot() (string, error) {
	cmd := exec.Command("git", "rev-parse", "--show-toplevel")
	output, err := cmd.Output()
	if err != nil {
		return "", fmt.Errorf("resolve repository root: %w", err)
	}
	root := strings.TrimSpace(string(output))
	if root == "" {
		return "", errors.New("repository root is empty")
	}
	return root, nil
}

// loadSchemas 加载全部 canonical schema，并在生成前闭合跨 schema 引用。
func loadSchemas(dir string) ([]renderedSchema, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, fmt.Errorf("read schema directory: %w", err)
	}
	var schemas []renderedSchema
	seen := map[string]bool{}
	for _, name := range canonicalSchemaNames(entries) {
		schema, err := loadSchema(filepath.Join(dir, name), name, seen)
		if err != nil {
			return nil, err
		}
		schemas = append(schemas, schema)
	}
	if len(schemas) != 3 {
		return nil, fmt.Errorf("expected exactly three canonical turn schemas, found %d", len(schemas))
	}
	if err := validateSchemaReferences(schemas); err != nil {
		return nil, err
	}
	sort.Slice(schemas, func(i, j int) bool { return schemas[i].name < schemas[j].name })
	return schemas, nil
}

func canonicalSchemaNames(entries []os.DirEntry) []string {
	var names []string
	for _, entry := range entries {
		if !entry.IsDir() && strings.HasSuffix(entry.Name(), ".json") && entry.Name() != "field_consumers.json" {
			names = append(names, entry.Name())
		}
	}
	return names
}

// loadSchema 解析一个 schema 并确保它的 id/title 在此次生成中唯一。
func loadSchema(path, name string, seen map[string]bool) (renderedSchema, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return renderedSchema{}, fmt.Errorf("read schema %s: %w", name, err)
	}
	var doc document
	if err := json.Unmarshal(raw, &doc); err != nil {
		return renderedSchema{}, fmt.Errorf("parse schema %s: %w", name, err)
	}
	if doc.ID == "" || doc.ID != doc.Title || seen[doc.ID] {
		return renderedSchema{}, fmt.Errorf("schema %s must have a unique matching $id and title", name)
	}
	seen[doc.ID] = true
	var normalized any
	if err := json.Unmarshal(raw, &normalized); err != nil {
		return renderedSchema{}, fmt.Errorf("normalize schema %s: %w", name, err)
	}
	references, err := validateSupportedSchemaDocument(normalized, name)
	if err != nil {
		return renderedSchema{}, err
	}
	canonical, err := json.MarshalIndent(normalized, "", "  ")
	if err != nil {
		return renderedSchema{}, fmt.Errorf("encode schema %s: %w", name, err)
	}
	return renderedSchema{name: doc.ID, raw: append(canonical, '\n'), references: references}, nil
}

func renderGo(schemas []renderedSchema) []byte {
	var output strings.Builder
	output.WriteString("// Code generated by go generate ./internal/dto/turn; DO NOT EDIT.\n\n")
	output.WriteString("package turn\n\n")
	output.WriteString("var generatedSchemas = map[string]string{\n")
	for _, schema := range schemas {
		fmt.Fprintf(&output, "\t%q: %s,\n", schema.name, strconvQuoteRaw(schema.raw))
	}
	output.WriteString("}\n")
	return []byte(output.String())
}

func renderJS(schemas []renderedSchema) ([]byte, error) {
	var output strings.Builder
	output.WriteString("// Code generated by go generate ./internal/dto/turn; DO NOT EDIT.\n\n")
	output.WriteString("const generatedSchemaMap = Object.create(null);\n")
	for index, schema := range schemas {
		var document any
		if err := json.Unmarshal(schema.raw, &document); err != nil {
			return nil, fmt.Errorf("decode normalized schema %s: %w", schema.name, err)
		}
		target := fmt.Sprintf("schema%d", index)
		fmt.Fprintf(&output, "let %s;\n", target)
		if err := renderJSValue(&output, target, document); err != nil {
			return nil, err
		}
		fmt.Fprintf(&output, "generatedSchemaMap[%q] = %s;\n", schema.name, target)
	}
	output.WriteString("export const generatedSchemas = Object.freeze(generatedSchemaMap);\n")
	return []byte(output.String()), nil
}

// renderJSValue 用逐项赋值生成扁平 JS，避免生成数据触发源码嵌套门禁。
func renderJSValue(output *strings.Builder, target string, value any) error {
	switch typed := value.(type) {
	case map[string]any:
		fmt.Fprintf(output, "%s = Object.create(null);\n", target)
		keys := make([]string, 0, len(typed))
		for key := range typed {
			keys = append(keys, key)
		}
		sort.Strings(keys)
		for _, key := range keys {
			if err := renderJSValue(output, target+"["+strconv.Quote(key)+"]", typed[key]); err != nil {
				return err
			}
		}
	case []any:
		fmt.Fprintf(output, "%s = [];\n", target)
		for index, item := range typed {
			if err := renderJSValue(output, fmt.Sprintf("%s[%d]", target, index), item); err != nil {
				return err
			}
		}
	default:
		encoded, err := json.Marshal(typed)
		if err != nil {
			return fmt.Errorf("encode generated JS scalar: %w", err)
		}
		fmt.Fprintf(output, "%s = %s;\n", target, encoded)
	}
	return nil
}

func strconvQuoteRaw(raw []byte) string {
	return "`" + strings.ReplaceAll(string(raw), "`", "`+\"`\"+`") + "`"
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "turn contract generator:", err)
	os.Exit(1)
}
