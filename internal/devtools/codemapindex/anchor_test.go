package codemapindex_test

import (
	"encoding/json"
	"os"
	"path/filepath"
	"runtime"
	"strings"
	"testing"

	"github.com/anthropic-ai/super-agent-v3/internal/devtools/codemapindex"
)

// projectRoot walks up from this test file to the repo root (where go.mod lives).
func projectRoot(t *testing.T) string {
	t.Helper()
	_, thisFile, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("runtime.Caller failed")
	}
	dir := filepath.Dir(thisFile)
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			t.Fatal("could not locate project root (go.mod not found)")
		}
		dir = parent
	}
}

// TestAIIndex_GeneratorAnchor verifies that the committed ai-index.json was
// produced by the canonical Go script (scripts/codemap_index.go) by checking
// for the generator anchor value. If someone regenerates the index with a
// Python/Node/etc. script the anchor will be absent or wrong, and this test
// will fail.
func TestAIIndex_GeneratorAnchor(t *testing.T) {
	root := projectRoot(t)
	indexPath := filepath.Join(root, "docs", "doc", "codemap", "ai-index.json")

	data, err := os.ReadFile(indexPath)
	if err != nil {
		t.Fatalf("failed to read ai-index.json: %v", err)
	}

	// ---- Sanity: no merge-conflict markers ----
	if strings.Contains(string(data), "<<<<<<<") || strings.Contains(string(data), ">>>>>>>") {
		t.Fatal("ai-index.json contains git merge-conflict markers; resolve conflicts and regenerate with `make codemap-refresh`")
	}

	// ---- Parse and validate generator anchor ----
	var idx struct {
		Generator string `json:"generator"`
	}
	if err := json.Unmarshal(data, &idx); err != nil {
		t.Fatalf("ai-index.json is not valid JSON: %v", err)
	}

	if idx.Generator != codemapindex.GeneratorAnchor {
		t.Fatalf(
			"ai-index.json generator mismatch:\n  got:  %q\n  want: %q\n\n"+
				"The index must be generated by the Go script.\n"+
				"Run: make codemap-refresh",
			idx.Generator, codemapindex.GeneratorAnchor,
		)
	}
}

// TestAIIndex_CompactFormat ensures the output is compact (single-line JSON),
// not pretty-printed. A pretty-printed 2.3MB file is unacceptable.
func TestAIIndex_CompactFormat(t *testing.T) {
	root := projectRoot(t)
	indexPath := filepath.Join(root, "docs", "doc", "codemap", "ai-index.json")

	data, err := os.ReadFile(indexPath)
	if err != nil {
		t.Fatalf("failed to read ai-index.json: %v", err)
	}

	lines := strings.Count(string(data), "\n")
	// Compact JSON from json.Marshal is a single line (0 or 1 newlines).
	// Allow up to 5 lines for minor formatting variance.
	if lines > 5 {
		t.Fatalf(
			"ai-index.json has %d lines; expected compact single-line JSON (≤5 lines).\n"+
				"Regenerate with: make codemap-refresh",
			lines,
		)
	}
}
