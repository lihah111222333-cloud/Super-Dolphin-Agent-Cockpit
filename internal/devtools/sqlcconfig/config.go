// Package sqlcconfig owns strict parsing and preflight validation for repository SQLC configurations.
package sqlcconfig

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"io"
	"os"
	"path"
	"path/filepath"
	"strings"
	"unicode"

	"gopkg.in/yaml.v3"
)

// Unit is one SQLC generation unit with repository-relative, canonical paths.
type Unit struct {
	ConfigPath, Queries, Output string
	Schemas                     []string
}

const (
	RootConfigPath                = "sqlc.yaml"
	RootOutputOwnerParent         = "internal/store"
	OrchestratorConfigPath        = "cmd/mcp-orch/sqlc.yaml"
	OrchestratorOutputOwnerParent = "cmd/mcp-orch/store"
	// GeneratedGoMarker 是 sqlc 生产 Go 文件的唯一 canonical ownership marker。
	GeneratedGoMarker = "// Code generated by sqlc. DO NOT EDIT.\n"
	// ManualExtensionMarker 是配置 output 内受保护手写扩展的唯一 ownership marker。
	ManualExtensionMarker = "// SQLC manual extension. DO NOT OVERWRITE.\n"
	// ManualTestExtensionMarker 是配置 output 内精确登记测试扩展的 ownership marker。
	ManualTestExtensionMarker = "// SQLC manual test extension. DO NOT OVERWRITE.\n"
)

// GoType represents the scalar or import/type form accepted by sqlc.
type GoType struct {
	Scalar string
	Import string
	Type   string
}
type configFile struct {
	Version string       `yaml:"version"`
	SQL     []configUnit `yaml:"sql"`
}
type configUnit struct {
	Engine        string   `yaml:"engine"`
	Queries       string   `yaml:"queries"`
	Schema        []string `yaml:"schema"`
	StrictOrderBy bool     `yaml:"strict_order_by"`
	Gen           struct {
		Go goConfig `yaml:"go"`
	} `yaml:"gen"`
}
type goConfig struct {
	Package                  string     `yaml:"package"`
	Out                      string     `yaml:"out"`
	EmitJSONTags             bool       `yaml:"emit_json_tags"`
	EmitDBTags               bool       `yaml:"emit_db_tags"`
	EmitEmptySlices          bool       `yaml:"emit_empty_slices"`
	EmitInterface            bool       `yaml:"emit_interface"`
	QueryParameterLimit      *int       `yaml:"query_parameter_limit"`
	OmitUnusedStructs        bool       `yaml:"omit_unused_structs"`
	EmitPointersForNullTypes bool       `yaml:"emit_pointers_for_null_types"`
	Initialisms              []string   `yaml:"initialisms"`
	Overrides                []override `yaml:"overrides"`
}
type override struct {
	Column string `yaml:"column"`
	GoType GoType `yaml:"go_type"`
}

// DefaultConfigPaths 返回仓库所有者唯一接受的 SQLC 配置路径。
func DefaultConfigPaths() []string { return []string{RootConfigPath, OrchestratorConfigPath} }

// LoadDefault 解析两个规范配置并校验路径与输出所有权，但不递归遍历目录树。
func LoadDefault(repoRoot string) ([]Unit, error) {
	git, err := ResolveExternalGit(repoRoot)
	if err != nil {
		return nil, err
	}
	return LoadDefaultWithGit(context.Background(), repoRoot, git)
}

// LoadDefaultWithGit binds config ownership checks to the caller's trusted Git runner.
func LoadDefaultWithGit(ctx context.Context, repoRoot string, git GitRunner) ([]Unit, error) {
	if ctx == nil {
		return nil, errors.New("SQLC Git context is required")
	}
	if strings.TrimSpace(repoRoot) == "" {
		return nil, errors.New("SQLC repository root is required")
	}
	var units []Unit
	for _, configPath := range DefaultConfigPaths() {
		config, err := readConfig(repoRoot, configPath)
		if err != nil {
			return nil, err
		}
		for index, rawUnit := range config.SQL {
			unit, err := resolveUnit(repoRoot, configPath, index, rawUnit)
			if err != nil {
				return nil, err
			}
			units = append(units, unit)
		}
	}
	if err := validateOutputDeclarations(ctx, repoRoot, units, git); err != nil {
		return nil, err
	}
	if err := ValidateOutputOwners(units); err != nil {
		return nil, err
	}
	if err := rejectStaleConfiguredOutputs(repoRoot, units); err != nil {
		return nil, err
	}
	return units, nil
}

// Preflight 执行 sqlc generate 前唯一权威且无副作用的检查。
func Preflight(repoRoot string) ([]Unit, error) {
	git, err := ResolveExternalGit(repoRoot)
	if err != nil {
		return nil, err
	}
	return PreflightWithGit(context.Background(), repoRoot, git)
}

// PreflightWithGit performs authoritative preflight with an explicit Git runner.
func PreflightWithGit(ctx context.Context, repoRoot string, git GitRunner) ([]Unit, error) {
	units, err := LoadDefaultWithGit(ctx, repoRoot, git)
	if err != nil {
		return nil, err
	}
	for _, unit := range units {
		if err := inspectTree(repoRoot, unit.Queries, treeQueries); err != nil {
			return nil, fmt.Errorf("SQLC queries tree %s: %w", unit.Queries, err)
		}
		for _, schema := range unit.Schemas {
			if err := inspectTree(repoRoot, schema, treeSchema); err != nil {
				return nil, fmt.Errorf("SQLC schema tree %s: %w", schema, err)
			}
		}
		if err := inspectTree(repoRoot, unit.Output, treeOutput); err != nil {
			return nil, fmt.Errorf("SQLC output tree %s: %w", unit.Output, err)
		}
	}
	return units, nil
}

// VerifyGeneratedOutputs 在生成后枚举所有 SQLC regular 文件并验证 Git 可见性。
func VerifyGeneratedOutputs(repoRoot string) error {
	if strings.TrimSpace(repoRoot) == "" {
		return errors.New("SQLC repository root is required")
	}
	git, err := ResolveExternalGit(repoRoot)
	if err != nil {
		return err
	}
	units, err := LoadDefaultWithGit(context.Background(), repoRoot, git)
	if err != nil {
		return err
	}
	return VerifyGeneratedUnitsWithGit(context.Background(), repoRoot, units, git)
}

// VerifyGeneratedUnits 使用预检时冻结的 unit 集合验证生成产物，避免运行期重载可变配置。
func VerifyGeneratedUnits(repoRoot string, units []Unit) error {
	git, err := ResolveExternalGit(repoRoot)
	if err != nil {
		return err
	}
	return VerifyGeneratedUnitsWithGit(context.Background(), repoRoot, units, git)
}

// VerifyGeneratedUnitsWithGit verifies frozen units through the caller's trusted Git runner.
func VerifyGeneratedUnitsWithGit(ctx context.Context, repoRoot string, units []Unit, git GitRunner) error {
	return verifyGeneratedUnits(ctx, repoRoot, units, git, generatedVerificationExact)
}

// VerifyGeneratedUnitsShapeWithGit 校验产物形态与 Git 可见性，但不要求相对 HEAD 或 index 无漂移。
func VerifyGeneratedUnitsShapeWithGit(ctx context.Context, repoRoot string, units []Unit, git GitRunner) error {
	return verifyGeneratedUnits(ctx, repoRoot, units, git, generatedVerificationShape)
}

type generatedVerificationMode uint8

const (
	generatedVerificationShape generatedVerificationMode = iota
	generatedVerificationExact
)

func verifyGeneratedUnits(ctx context.Context, repoRoot string, units []Unit, git GitRunner, mode generatedVerificationMode) error {
	if ctx == nil {
		return errors.New("SQLC Git context is required")
	}
	if strings.TrimSpace(repoRoot) == "" {
		return errors.New("SQLC repository root is required")
	}
	if len(units) == 0 {
		return errors.New("SQLC generated unit set is empty")
	}
	if err := ValidateOutputOwners(units); err != nil {
		return err
	}
	if err := verifyRequiredManualExtensions(repoRoot, units); err != nil {
		return err
	}
	for _, unit := range units {
		if err := verifyGeneratedOutputTree(ctx, repoRoot, unit, git, mode); err != nil {
			return fmt.Errorf("verify SQLC output tree %s: %w", unit.Output, err)
		}
	}
	return nil
}

// verifyGeneratedOutputTree 收集一个已配置输出树中的 regular 文件并检查其 Git 状态。
func verifyGeneratedOutputTree(ctx context.Context, repoRoot string, unit Unit, git GitRunner, mode generatedVerificationMode) error {
	files, err := loadGeneratedOutputFiles(repoRoot, unit.Output)
	if err != nil {
		return err
	}
	generatedGoFiles, err := verifyGeneratedOutputFiles(ctx, repoRoot, unit, files, git, mode)
	if err != nil {
		return err
	}
	if generatedGoFiles == 0 {
		return errors.New("empty generated output contains no SQLC-generated Go file")
	}
	return nil
}

func loadGeneratedOutputFiles(repoRoot, relative string) ([]string, error) {
	absolute := filepath.Join(repoRoot, filepath.FromSlash(relative))
	info, err := os.Lstat(absolute)
	if errors.Is(err, os.ErrNotExist) {
		return nil, errors.New("generated output directory is missing")
	}
	if err != nil {
		return nil, err
	}
	if info.Mode()&os.ModeSymlink != 0 || !info.IsDir() {
		return nil, errors.New("generated output must be a regular directory")
	}
	if !outputPermissionAllowed(info, true) {
		return nil, fmt.Errorf("generated output directory has forbidden permissions %04o", info.Mode().Perm())
	}
	files := make([]string, 0)
	if err := collectGeneratedOutputFiles(absolute, relative, &files); err != nil {
		return nil, err
	}
	if len(files) == 0 {
		return nil, errors.New("generated output directory is empty")
	}
	return files, nil
}

func verifyGeneratedOutputFiles(ctx context.Context, repoRoot string, unit Unit, files []string, git GitRunner, mode generatedVerificationMode) (int, error) {
	generatedGoFiles := 0
	for _, file := range files {
		if strings.HasSuffix(file, "_test.go") {
			if err := verifyManualTestExtension(repoRoot, unit, file); err != nil {
				return 0, err
			}
			if err := verifyGeneratedGitState(ctx, repoRoot, file, git, mode); err != nil {
				return 0, err
			}
			continue
		}
		if filepath.Ext(file) == ".go" {
			generated, err := verifyGeneratedGoMarker(repoRoot, unit, file)
			if err != nil {
				return 0, err
			}
			if generated {
				generatedGoFiles++
			}
		}
		if err := verifyGeneratedGitState(ctx, repoRoot, file, git, mode); err != nil {
			return 0, err
		}
	}
	return generatedGoFiles, nil
}

// verifyGeneratedGoMarker 拒绝输出目录中冒充 sqlc 产物的手写 Go 文件。
func verifyGeneratedGoMarker(repoRoot string, unit Unit, relative string) (bool, error) {
	data, err := os.ReadFile(filepath.Join(repoRoot, filepath.FromSlash(relative)))
	if err != nil {
		return false, fmt.Errorf("read generated SQLC file %s: %w", relative, err)
	}
	if bytes.HasPrefix(data, []byte(GeneratedGoMarker)) {
		return true, nil
	}
	if bytes.HasPrefix(data, []byte(ManualExtensionMarker)) && manualExtensionAllowed(unit, relative) {
		return false, nil
	}
	return false, fmt.Errorf("generated SQLC file %s lacks canonical sqlc marker", relative)
}

func manualExtensionAllowed(unit Unit, relative string) bool {
	return IsManualExtension(unit, relative)
}

// collectGeneratedOutputFiles 递归收集输出 regular 文件并复用输出树的硬链接检查。
func collectGeneratedOutputFiles(absolute, relative string, files *[]string) error {
	entries, err := os.ReadDir(absolute)
	if err != nil {
		return err
	}
	for _, entry := range entries {
		childAbsolute := filepath.Join(absolute, entry.Name())
		childRelative := path.Join(relative, entry.Name())
		if err := collectGeneratedOutputEntry(childAbsolute, childRelative, files); err != nil {
			return err
		}
	}
	return nil
}

func collectGeneratedOutputEntry(absolute, relative string, files *[]string) error {
	info, err := os.Lstat(absolute)
	if err != nil {
		return err
	}
	if info.Mode()&os.ModeSymlink != 0 {
		return fmt.Errorf("symbolic link is forbidden at %s", relative)
	}
	if info.IsDir() {
		return collectGeneratedOutputDirectory(absolute, relative, info, files)
	}
	return collectGeneratedOutputFile(absolute, relative, info, files)
}

func collectGeneratedOutputDirectory(absolute, relative string, info os.FileInfo, files *[]string) error {
	if !outputPermissionAllowed(info, true) {
		return fmt.Errorf("generated output directory %s has forbidden permissions %04o", relative, info.Mode().Perm())
	}
	return collectGeneratedOutputFiles(absolute, relative, files)
}

func collectGeneratedOutputFile(absolute, relative string, info os.FileInfo, files *[]string) error {
	if err := validateTreeEntry(absolute, info, relative, treeOutput); err != nil {
		return err
	}
	if filepath.Ext(relative) != ".go" && filepath.Base(relative) != ".gitkeep" {
		return fmt.Errorf("unexpected non-Go file in SQLC output: %s", relative)
	}
	if !outputPermissionAllowed(info, false) {
		return fmt.Errorf("generated output file %s has forbidden permissions %04o", relative, info.Mode().Perm())
	}
	*files = append(*files, relative)
	return nil
}

func outputPermissionAllowed(info os.FileInfo, directory bool) bool {
	permissions := info.Mode().Perm()
	if directory {
		return permissions == 0o755 || permissions == 0o700
	}
	return permissions == 0o644 || permissions == 0o600
}

// UnmarshalYAML 严格接受 sqlc 的标量或 import/type go_type 形式。
func (value *GoType) UnmarshalYAML(node *yaml.Node) error {
	if node.Kind == yaml.ScalarNode {
		text, err := yamlString(node, "go_type scalar")
		if err != nil {
			return err
		}
		value.Scalar = text
		return nil
	}
	fields, err := decodeGoTypeFields(node)
	if err != nil {
		return err
	}
	value.Import, value.Type = fields["import"], fields["type"]
	return nil
}

// decodeGoTypeFields 解析 go_type 映射并拒绝重复、未知或空字段。
func decodeGoTypeFields(node *yaml.Node) (map[string]string, error) {
	if node.Kind != yaml.MappingNode || len(node.Content) == 0 {
		return nil, errors.New("go_type mapping must be non-empty")
	}
	fields := map[string]string{}
	for index := 0; index < len(node.Content); index += 2 {
		key, value, err := decodeGoTypeField(node.Content[index], node.Content[index+1])
		if err != nil {
			return nil, err
		}
		if _, exists := fields[key]; exists {
			return nil, fmt.Errorf("go_type field %q is duplicated", key)
		}
		fields[key] = value
	}
	if fields["import"] == "" || fields["type"] == "" {
		return nil, errors.New("go_type mapping must contain non-blank import and type fields")
	}
	return fields, nil
}
func decodeGoTypeField(keyNode, valueNode *yaml.Node) (string, string, error) {
	key, err := yamlString(keyNode, "go_type field name")
	if err != nil {
		return "", "", err
	}
	if key != "import" && key != "type" {
		return "", "", fmt.Errorf("go_type field %q is unknown", key)
	}
	value, err := yamlString(valueNode, "go_type field "+key)
	return key, value, err
}
func yamlString(node *yaml.Node, label string) (string, error) {
	if node.Kind != yaml.ScalarNode || node.Tag != "!!str" || strings.TrimSpace(node.Value) == "" {
		return "", fmt.Errorf("%s must be a non-blank YAML string", label)
	}
	return node.Value, nil
}

// readConfig 读取单个规范 SQLC 配置并拒绝未知字段或多文档内容。
func readConfig(repoRoot, configPath string) (configFile, error) {
	if err := requirePath(repoRoot, configPath, false, false); err != nil {
		return configFile{}, fmt.Errorf("inspect canonical %s SQLC config: %w", configPath, err)
	}
	raw, err := os.ReadFile(filepath.Join(repoRoot, filepath.FromSlash(configPath)))
	if err != nil {
		return configFile{}, fmt.Errorf("read SQLC config %s: %w", configPath, err)
	}
	var config configFile
	decoder := yaml.NewDecoder(bytes.NewReader(raw))
	decoder.KnownFields(true)
	if err := decoder.Decode(&config); err != nil {
		return configFile{}, fmt.Errorf("parse SQLC config %s: %w", configPath, err)
	}
	if err := decoder.Decode(&yaml.Node{}); err != io.EOF {
		return configFile{}, fmt.Errorf("SQLC config %s must contain a single document: %v", configPath, err)
	}
	if config.Version != "2" || len(config.SQL) == 0 {
		return configFile{}, fmt.Errorf("SQLC config %s must use version 2 with non-empty sql", configPath)
	}
	return config, nil
}

// resolveUnit 将原始 SQLC 单元解析为仓库相对的规范路径。
func resolveUnit(repoRoot, configPath string, index int, raw configUnit) (Unit, error) {
	if err := validateConfigUnit(configPath, index, raw); err != nil {
		return Unit{}, err
	}
	queries, err := resolvePath(repoRoot, configPath, raw.Queries, true, false)
	if err != nil {
		return Unit{}, fmt.Errorf("SQLC config %s sql[%d] queries: %w", configPath, index, err)
	}
	output, err := resolvePath(repoRoot, configPath, raw.Gen.Go.Out, true, true)
	if err != nil {
		return Unit{}, fmt.Errorf("SQLC config %s sql[%d] output: %w", configPath, index, err)
	}
	unit := Unit{ConfigPath: configPath, Queries: queries, Output: output}
	for schemaIndex, schema := range raw.Schema {
		resolved, err := resolvePath(repoRoot, configPath, schema, false, false)
		if err != nil {
			return Unit{}, fmt.Errorf("SQLC config %s sql[%d] schema[%d]: %w", configPath, index, schemaIndex, err)
		}
		unit.Schemas = append(unit.Schemas, resolved)
	}
	return unit, nil
}

// validateConfigUnit 校验 SQLC 单元的引擎、schema 与 Go 生成参数。
func validateConfigUnit(configPath string, index int, raw configUnit) error {
	if raw.Engine != "sqlite" || len(raw.Schema) == 0 {
		return fmt.Errorf("SQLC config %s sql[%d] must use sqlite with non-empty schema", configPath, index)
	}
	if strings.TrimSpace(raw.Gen.Go.Package) == "" {
		return fmt.Errorf("SQLC config %s sql[%d] go.package is required", configPath, index)
	}
	if err := validateGenerationSafetyOptions(configPath, index, raw); err != nil {
		return err
	}
	for _, item := range raw.Gen.Go.Overrides {
		if strings.TrimSpace(item.Column) == "" || item.GoType == (GoType{}) {
			return fmt.Errorf("SQLC config %s sql[%d] override column and go_type are required", configPath, index)
		}
	}
	return nil
}

func validateGenerationSafetyOptions(configPath string, index int, raw configUnit) error {
	if !raw.StrictOrderBy {
		return fmt.Errorf("SQLC config %s sql[%d] must enable strict_order_by", configPath, index)
	}
	if configPath == RootConfigPath && !raw.Gen.Go.EmitInterface {
		return fmt.Errorf("SQLC config %s sql[%d] must enable emit_interface", configPath, index)
	}
	if raw.Gen.Go.QueryParameterLimit == nil || *raw.Gen.Go.QueryParameterLimit != 0 {
		return fmt.Errorf("SQLC config %s sql[%d] must pin query_parameter_limit to 0", configPath, index)
	}
	return nil
}

// resolvePath 规范化配置路径并拒绝仓库边界外或不安全的目标。
func resolvePath(repoRoot, configPath, configured string, wantDirectory, allowMissing bool) (string, error) {
	normalized, err := canonicalConfiguredPath(configured)
	if err != nil {
		return "", err
	}
	resolved := path.Clean(path.Join(path.Dir(configPath), normalized))
	if resolved == "." || resolved == ".." || strings.HasPrefix(resolved, "../") {
		return "", fmt.Errorf("path %q escapes repository", configured)
	}
	if err := requirePath(repoRoot, resolved, wantDirectory, allowMissing); err != nil {
		return "", fmt.Errorf("inspect configured path %s: %w", resolved, err)
	}
	return resolved, nil
}

// canonicalConfiguredPath 验证 SQLC 约定的仓库相对路径语法。
func canonicalConfiguredPath(configured string) (string, error) {
	if err := validateConfiguredPathSyntax(configured); err != nil {
		return "", err
	}
	cleaned := path.Clean(configured)
	if cleaned == "." || cleaned == ".." {
		return "", fmt.Errorf("path %q must not name a configuration or parent directory", configured)
	}
	if err := validateConfiguredPathComponents(configured, cleaned); err != nil {
		return "", err
	}
	// The sqlc convention documents directory paths with one trailing slash;
	// accept that spelling while rejecting other non-canonical components.
	if configured != cleaned && strings.TrimSuffix(configured, "/") != cleaned {
		return "", fmt.Errorf("path %q must be normalized (a single trailing slash is allowed)", configured)
	}
	return cleaned, nil
}

// validateConfiguredPathSyntax 拒绝绝对路径、空白、glob 与 shell 歧义。
func validateConfiguredPathSyntax(configured string) error {
	if configured == "" {
		return fmt.Errorf("path %q must be a non-blank repository-relative path", configured)
	}
	if path.IsAbs(configured) || filepath.IsAbs(filepath.FromSlash(configured)) {
		return fmt.Errorf("path %q must be a non-blank repository-relative path", configured)
	}
	if strings.Contains(configured, `\`) || strings.IndexFunc(configured, unicode.IsSpace) >= 0 {
		return fmt.Errorf("path %q must be a non-blank repository-relative path", configured)
	}
	if strings.ContainsAny(configured, "*?[]") {
		return fmt.Errorf("path %q must not contain glob metacharacters", configured)
	}
	return nil
}

func validateConfiguredPathComponents(configured, cleaned string) error {
	for component := range strings.SplitSeq(cleaned, "/") {
		if strings.HasPrefix(component, "-") {
			return fmt.Errorf("path %q contains a leading-dash component", configured)
		}
		if strings.Contains(component, ":") {
			return fmt.Errorf("path %q contains a colon or Windows drive component", configured)
		}
	}
	return nil
}

// requirePath 递归 Lstat 配置路径并拒绝 symlink、非目录祖先和非 regular 文件。
func requirePath(repoRoot, relative string, wantDirectory, allowMissing bool) error {
	current := repoRoot
	parts := strings.Split(filepath.ToSlash(relative), "/")
	for index, part := range parts {
		current = filepath.Join(current, filepath.FromSlash(part))
		info, err := os.Lstat(current)
		if err != nil {
			if missingAllowed(err, allowMissing) {
				return nil
			}
			return err
		}
		if info.Mode()&os.ModeSymlink != 0 {
			return fmt.Errorf("symbolic link is forbidden at %s", path.Join(parts[:index+1]...))
		}
		last := index == len(parts)-1
		if !last && !info.IsDir() {
			return fmt.Errorf("configured ancestor %s is not a directory", path.Join(parts[:index+1]...))
		}
		if invalidPathEntry(info, last, wantDirectory) {
			return fmt.Errorf("configured path has unexpected directory type or is not regular")
		}
	}
	return nil
}
func missingAllowed(err error, allowMissing bool) bool {
	return allowMissing && errors.Is(err, os.ErrNotExist)
}
func invalidPathEntry(info os.FileInfo, last, wantDirectory bool) bool {
	if !last {
		return !info.IsDir()
	}
	if info.IsDir() != wantDirectory {
		return true
	}
	return !wantDirectory && !info.Mode().IsRegular()
}

type treeKind uint8

const (
	treeQueries treeKind = iota
	treeSchema
	treeOutput
)

func inspectTree(repoRoot, relative string, kind treeKind) error {
	return inspectTreePath(filepath.Join(repoRoot, filepath.FromSlash(relative)), relative, kind)
}

// inspectTreePath 递归检查 queries、schema 或 output 树而不产生副作用。
func inspectTreePath(absolute, relative string, kind treeKind) error {
	info, err := os.Lstat(absolute)
	if err != nil {
		if kind == treeOutput && errors.Is(err, os.ErrNotExist) {
			return nil
		}
		return err
	}
	if info.Mode()&os.ModeSymlink != 0 {
		return fmt.Errorf("symbolic link is forbidden at %s", relative)
	}
	if info.IsDir() {
		return inspectTreeDirectory(absolute, relative, kind)
	}
	return validateTreeEntry(absolute, info, relative, kind)
}

func inspectTreeDirectory(absolute, relative string, kind treeKind) error {
	entries, err := os.ReadDir(absolute)
	if err != nil {
		return err
	}
	for _, entry := range entries {
		child := path.Join(relative, entry.Name())
		if err := inspectTreePath(filepath.Join(absolute, entry.Name()), child, kind); err != nil {
			return err
		}
	}
	return nil
}

func validateTreeEntry(absolute string, info os.FileInfo, relative string, kind treeKind) error {
	if !info.Mode().IsRegular() {
		return fmt.Errorf("non-regular %s entry is forbidden", []string{"query", "schema", "output"}[kind])
	}
	if kind == treeOutput {
		links, err := hardLinkCount(absolute, info)
		if err != nil {
			return fmt.Errorf("inspect output link count at %s: %w", relative, err)
		}
		if links > 1 {
			return fmt.Errorf("output hard link is forbidden at %s", relative)
		}
	}
	return nil
}

// validateOutputDeclarations 校验输出所有权及其与所有输入树的冲突。
func validateOutputDeclarations(ctx context.Context, repoRoot string, units []Unit, git GitRunner) error {
	for _, unit := range units {
		if err := validateOutputOwnership(ctx, repoRoot, unit.Output, git); err != nil {
			return err
		}
	}
	for index, current := range units {
		for previousIndex := range index {
			previous := units[previousIndex]
			if err := rejectOutputPathConflict(repoRoot, previous.Output, current.Output, "output"); err != nil {
				return err
			}
		}
	}
	for _, unit := range units {
		for _, other := range units {
			roles := append([]configuredTree{{kind: "queries", relative: other.Queries}}, configuredTrees("schema", other.Schemas)...)
			for _, role := range roles {
				if err := rejectOutputPathConflict(repoRoot, unit.Output, role.relative, role.kind); err != nil {
					return err
				}
			}
		}
	}
	return nil
}

type configuredTree struct {
	kind     string
	relative string
}

func configuredTrees(kind string, paths []string) []configuredTree {
	trees := make([]configuredTree, 0, len(paths))
	for _, relative := range paths {
		trees = append(trees, configuredTree{kind: kind, relative: relative})
	}
	return trees
}

// rejectOutputPathConflict 拒绝输出与另一配置树的逻辑或物理重叠。
func rejectOutputPathConflict(repoRoot, output, other, otherKind string) error {
	if outputPathsOverlap(output, other) {
		return fmt.Errorf("SQLC output %s overlaps %s tree %s (duplicate or ancestor/descendant)", output, otherKind, other)
	}
	outputInfo, outputExists, err := outputInfo(repoRoot, output)
	if err != nil {
		return err
	}
	otherInfo, otherExists, err := configuredTreeInfo(repoRoot, other, otherKind)
	if err != nil {
		return err
	}
	if outputExists && otherExists && os.SameFile(outputInfo, otherInfo) {
		return fmt.Errorf("SQLC output %s aliases the same physical %s tree %s", output, otherKind, other)
	}
	return nil
}

func configuredTreeInfo(repoRoot, relative, kind string) (os.FileInfo, bool, error) {
	info, err := os.Lstat(filepath.Join(repoRoot, filepath.FromSlash(relative)))
	if errors.Is(err, os.ErrNotExist) {
		return nil, false, nil
	}
	if err != nil {
		return nil, false, fmt.Errorf("inspect SQLC %s %s: %w", kind, relative, err)
	}
	if info.Mode()&os.ModeSymlink != 0 {
		return nil, false, fmt.Errorf("SQLC %s %s is a symbolic link", kind, relative)
	}
	return info, true, nil
}

// validateOutputOwnership 拒绝 .git 或 Git 忽略的输出路径并保持所有权可见。
func validateOutputOwnership(ctx context.Context, repoRoot, output string, git GitRunner) error {
	if pathContainsGitMetadata(output) {
		return fmt.Errorf("SQLC output %s is under .git metadata", output)
	}
	// Check both the configured root and a representative generated Go file. The
	// latter catches patterns such as *.go that would otherwise let an empty,
	// missing output directory pass while generated files remain ignored.
	for _, candidate := range []string{output, path.Join(output, ".sqlc-output-owner-probe.go")} {
		err := git.run(ctx, repoRoot, "check-ignore", "--no-index", "--quiet", "--", candidate)
		if err == nil {
			return fmt.Errorf("SQLC output %s is Git-ignored; generated output must be tracked or non-ignored", output)
		}
		if gitExitCode(err, 1) {
			continue
		}
		return fmt.Errorf("check Git ownership for SQLC output %s: %w", output, err)
	}
	return nil
}

func pathContainsGitMetadata(relative string) bool {
	for component := range strings.SplitSeq(path.Clean(relative), "/") {
		if strings.EqualFold(component, ".git") {
			return true
		}
	}
	return false
}
func outputInfo(repoRoot, relative string) (os.FileInfo, bool, error) {
	info, err := os.Lstat(filepath.Join(repoRoot, filepath.FromSlash(relative)))
	if errors.Is(err, os.ErrNotExist) {
		return nil, false, nil
	}
	if err != nil {
		return nil, false, fmt.Errorf("inspect SQLC output %s: %w", relative, err)
	}
	if info.Mode()&os.ModeSymlink != 0 {
		return nil, false, fmt.Errorf("SQLC output %s is a symbolic link", relative)
	}
	return info, true, nil
}
func outputPathsOverlap(left, right string) bool {
	left = path.Clean(left)
	right = path.Clean(right)
	return strings.EqualFold(left, right) || caseFoldPathAncestor(left, right) || caseFoldPathAncestor(right, left)
}

func caseFoldPathAncestor(ancestor, candidate string) bool {
	ancestorParts := strings.Split(ancestor, "/")
	candidateParts := strings.Split(candidate, "/")
	if len(candidateParts) <= len(ancestorParts) {
		return false
	}
	for index, component := range ancestorParts {
		if !strings.EqualFold(component, candidateParts[index]) {
			return false
		}
	}
	return true
}
