		environment := []string{assignment}
		if strings.EqualFold(assignment, "GOWORK=off") {
			environment = []string{"GOWORK=off", assignment}
		}
		if strings.HasSuffix(assignment, "=0") {
			environment = []string{"GIT_OPTIONAL_LOCKS=0", assignment}
		}
		err = runSQLCVerify(context.Background(), gitBinary, "/bin/false", goFmtBinary, source, environment, ioDiscard{}, ioDiscard{})
