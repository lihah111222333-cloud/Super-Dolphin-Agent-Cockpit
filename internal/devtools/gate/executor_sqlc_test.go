func TestRunSQLCVerifyCancellationBoundsDeferredSnapshot(t *testing.T) {
	if runtime.GOOS == "windows" {
		t.Skip("Unix shell fixture")
	}
	gitBinary, err := exec.LookPath("git")
	if err != nil {
		t.Fatal("git is required")
	}
	source := newExecutorGitSnapshot(t, map[string]string{"placeholder.txt": "fixture\n"})
	writeRealSQLCInputs(t, source)
	sqlcBinary := filepath.Join(t.TempDir(), "sqlc")
	if err := os.WriteFile(sqlcBinary, []byte("#!/bin/sh\nsleep 5\n"), 0o700); err != nil {
		t.Fatal(err)
	}
	cause := errors.New("remote SQLC workload deadline")
	ctx, cancel := context.WithTimeoutCause(context.Background(), 500*time.Millisecond, cause)
	defer cancel()
	started := time.Now()
	err = runSQLCVerify(ctx, gitBinary, sqlcBinary, sqlcTestGoFmtBinary(t), source, []string{"GOWORK=off"}, ioDiscard{}, ioDiscard{})
	if !errors.Is(err, context.DeadlineExceeded) || !errors.Is(err, cause) {
		t.Fatalf("runSQLCVerify() error = %v, want deadline and custom cause", err)
	}
	if elapsed := time.Since(started); elapsed > 2*time.Second {
		t.Fatalf("runSQLCVerify() elapsed = %v, deferred snapshot outlived cancellation", elapsed)
	}
}

