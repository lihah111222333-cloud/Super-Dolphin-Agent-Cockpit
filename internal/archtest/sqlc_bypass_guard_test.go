var wildcardRowSQLPattern = regexp.MustCompile(`(?is)\b(SELECT|RETURNING)\s+\*`)

func TestSQLCGeneratedGuardRequiresExplicitRepoRootAndParserSuccess(t *testing.T) {
	marker := []byte("// Code generated by sqlc. DO NOT EDIT.\npackage sqlc\n")
	if _, err := IsGeneratedSQLCFile(CheckOptions{}, "internal/store/sqlc/generated.go", marker); err == nil {
		t.Fatal("IsGeneratedSQLCFile accepted missing explicit RepoRoot")
	}
	root := t.TempDir()
	if err := os.WriteFile(filepath.Join(root, "sqlc.yaml"), []byte("version: 2\nunknown: true\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if _, err := IsGeneratedSQLCFile(CheckOptions{RepoRoot: root}, "internal/store/sqlc/generated.go", marker); err == nil {
		t.Fatal("IsGeneratedSQLCFile accepted malformed SQLC parser input")
	}
}

func TestSQLCOwnerRejectsOutputOutsideSafeParent(t *testing.T) {
	root := t.TempDir()
	writeCanonicalSQLCGuardFixture(t, root)
	configPath := filepath.Join(root, "sqlc.yaml")
	config, err := os.ReadFile(configPath)
	if err != nil {
		t.Fatal(err)
	}
	config = []byte(strings.Replace(string(config), "out: internal/store/sqlc", "out: generated/out", 1))
	if err := os.WriteFile(configPath, config, 0o644); err != nil {
		t.Fatal(err)
	}
	if _, err := configuredSQLCOutputDirs(CheckOptions{RepoRoot: root}); err == nil || !strings.Contains(err.Error(), "strict descendant") {
		t.Fatalf("configuredSQLCOutputDirs() error = %v, want safe owner parent rejection", err)
	}
}

func TestSQLCGeneratedGuardFollowsDynamicConfiguredOutput(t *testing.T) {
	root := t.TempDir()
	writeCanonicalSQLCGuardFixture(t, root)
	rewriteRootSQLCOutput(t, root, "internal/store/sqlc-alt")
	generatedRel := "internal/store/sqlc-alt/generated.go"
	generatedPath := writeSQLCBoundaryFixtureFile(t, root, generatedRel, "// Code generated by sqlc. DO NOT EDIT.\npackage sqlc\n")
	assertGeneratedSQLCBoundarySkip(t, root, generatedPath, generatedRel)
	leakRel := "internal/module/leak.go"
	leak := "package module\nimport _ \"github.com/lihah111222333-cloud/super-dolphin-agent/internal/store/sqlc-alt\"\n"
	leakPath := writeSQLCBoundaryFixtureFile(t, root, leakRel, leak)
	assertConfiguredSQLCImportDenied(t, root, leakPath, leakRel, "internal/store/sqlc-alt")
}

func rewriteRootSQLCOutput(t *testing.T, root, output string) {
	t.Helper()
	configPath := filepath.Join(root, "sqlc.yaml")
	config, err := os.ReadFile(configPath)
	if err != nil {
		t.Fatal(err)
	}
	config = []byte(strings.Replace(string(config), "out: internal/store/sqlc", "out: "+output, 1))
	if err := os.WriteFile(configPath, config, 0o644); err != nil {
		t.Fatal(err)
	}
}

func writeSQLCBoundaryFixtureFile(t *testing.T, root, relative, content string) string {
	t.Helper()
	file := filepath.Join(root, filepath.FromSlash(relative))
	if err := os.MkdirAll(filepath.Dir(file), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(file, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
	return file
}

func assertGeneratedSQLCBoundarySkip(t *testing.T, root, file, relative string) {
	t.Helper()
	violations, err := EvaluateBackendBoundaryFile(root, file, relative, DefaultBackendBoundaryRegistry(), "store_sqlc_store_platform_only")
	if err != nil {
		t.Fatalf("EvaluateBackendBoundaryFile() error = %v", err)
	}
	if len(violations) != 0 {
		t.Fatalf("dynamic configured SQLC output violations = %v, want generated marker skip", violations)
	}
}

func assertConfiguredSQLCImportDenied(t *testing.T, root, file, relative, importFragment string) {
	t.Helper()
	violations, err := EvaluateBackendBoundaryFile(root, file, relative, DefaultBackendBoundaryRegistry(), "store_sqlc_store_platform_only")
	if err != nil {
		t.Fatalf("EvaluateBackendBoundaryFile(dynamic import) error = %v", err)
	}
	if len(violations) == 0 || !strings.Contains(strings.Join(violations, "\n"), importFragment) {
		t.Fatalf("dynamic configured SQLC import bypassed boundary: %v", violations)
	}
}

func TestMCPOrchDAGStorageDoesNotBypassSQLC(t *testing.T) {
	t.Parallel()

	root := repoRootForGuardTests(t)
	checked := collectDAGSQLCGuardFiles(t, root)
	var violations []string
	for _, rel := range checked {
		path := filepath.Join(root, rel)
		violations = append(violations, rawSQLCallViolations(t, root, path, rel)...)
	}
	if len(violations) > 0 {
		t.Fatalf("mcp-orch DAG storage must use sqlc query methods, found bypasses:\n%s", strings.Join(violations, "\n"))
	}
}

func TestMCPOrchSQLCGeneratedPackageHasNoHandWrittenDBAccessors(t *testing.T) {
	t.Parallel()

	root := repoRootForGuardTests(t)
	sqlcDir := sqlcOutputDirForConfig(t, root, "cmd/mcp-orch/sqlc.yaml")
	assertForbiddenSQLCFilesAbsent(t, sqlcDir)
	assertMCPOrchSQLCProductionFilesGenerated(t, sqlcDir)
}

func sqlcOutputDirForConfig(t *testing.T, root, configPath string) string {
	t.Helper()
	units, err := sqlcconfig.LoadDefault(root)
	if err != nil {
		t.Fatalf("load canonical SQLC output owner: %v", err)
	}
	for _, unit := range units {
		if unit.ConfigPath == configPath {
			return filepath.Join(root, filepath.FromSlash(unit.Output))
		}
	}
	t.Fatalf("SQLC config %s has no output unit", configPath)
	return ""
}

func assertForbiddenSQLCFilesAbsent(t *testing.T, sqlcDir string) {
	t.Helper()
	for _, name := range []string{
		"db_accessor.go",
		"db_ext.go",
		"task_dag_node_lookup.sql.go",
		"task_dag_node_write_batch.go",
	} {
		path := filepath.Join(sqlcDir, name)
		if _, err := os.Stat(path); err == nil {
			t.Fatalf("%s exists; configured SQLC output must remain generated-only except approved type helpers", path)
		} else if !os.IsNotExist(err) {
			t.Fatalf("stat %s: %v", path, err)
		}
	}
}

func assertMCPOrchSQLCProductionFilesGenerated(t *testing.T, sqlcDir string) {
	t.Helper()
	entries, err := os.ReadDir(sqlcDir)
	if err != nil {
		t.Fatalf("read %s: %v", sqlcDir, err)
	}
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") || name == "types_ext.go" {
			continue
		}
		path := filepath.Join(sqlcDir, name)
		data, err := os.ReadFile(path)
		if err != nil {
			t.Fatalf("read %s: %v", path, err)
		}
		if !strings.HasPrefix(string(data), "// Code generated by sqlc. DO NOT EDIT.") {
			t.Fatalf("%s is not sqlc-generated; put hand-written helpers outside the configured SQLC output", path)
		}
	}
}

func TestMCPOrchSQLQueriesUseExplicitColumns(t *testing.T) {
	t.Parallel()

	root := repoRootForGuardTests(t)
	queryDir := filepath.Join(root, "cmd", "mcp-orch", "sql", "queries")
	var violations []string
	err := filepath.WalkDir(queryDir, func(path string, entry os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() || !strings.HasSuffix(path, ".sql") {
			return nil
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if wildcardRowSQLPattern.Match(data) {
			rel, err := filepath.Rel(root, path)
			if err != nil {
				return err
			}
			violations = append(violations, rel)
		}
		return nil
	})
	if err != nil {
		t.Fatalf("walk %s: %v", queryDir, err)
	}
	if len(violations) > 0 {
		t.Fatalf("mcp-orch sqlc queries must enumerate columns instead of SELECT */RETURNING *:\n%s", strings.Join(violations, "\n"))
	}
}

func collectDAGSQLCGuardFiles(t *testing.T, root string) []string {
	t.Helper()
	var checked []string
	checked = appendGoFilesUnder(t, root, checked, filepath.Join("cmd", "mcp-orch", "store", "taskdag"))
	checked = appendGoFilesUnder(t, root, checked, filepath.Join("cmd", "mcp-orch", "orchestration", "cron"))
	checked = appendGoFilesUnder(t, root, checked, filepath.Join("cmd", "mcp-orch", "fxadapter"))
	checked = appendGoFilesUnder(t, root, checked, filepath.Join("cmd", "mcp-orch", "store", "sqlctx"))
	return append(checked, filepath.Join("cmd", "mcp-orch", "dag_cron_runner.go"))
}

func rawSQLCallViolations(t *testing.T, root, path, rel string) []string {
	t.Helper()

	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, path, nil, 0)
	if err != nil {
		t.Fatalf("parse %s: %v", rel, err)
	}
	var violations []string
	ast.Inspect(file, func(node ast.Node) bool {
		call, ok := node.(*ast.CallExpr)
		if !ok {
			return true
		}
		selector, ok := call.Fun.(*ast.SelectorExpr)
		if !ok || !isRawDBCall(selector.Sel.Name) {
			return true
		}
		position := fset.Position(selector.Sel.Pos())
		relPosition, err := filepath.Rel(root, position.Filename)
		if err != nil {
			relPosition = position.Filename
		}
		violations = append(violations, fmt.Sprintf("%s:%d calls .%s", relPosition, position.Line, selector.Sel.Name))
		return true
	})
	return violations
}

func isRawDBCall(name string) bool {
	switch name {
	case "Exec", "Query", "QueryRow":
		return true
	default:
		return false
	}
}

func appendGoFilesUnder(t *testing.T, root string, out []string, relDir string) []string {
	t.Helper()
	dir := filepath.Join(root, relDir)
	err := filepath.WalkDir(dir, func(path string, entry os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() || !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
			return nil
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		out = append(out, rel)
		return nil
	})
	if err != nil {
		t.Fatalf("walk %s: %v", relDir, err)
	}
	return out
}
