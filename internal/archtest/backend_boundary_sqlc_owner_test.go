func TestConfiguredSQLCOutputRebindsStoreDependencyPrivilege(t *testing.T) {
	root := t.TempDir()
	writeCanonicalSQLCGuardFixture(t, root)
	configPath := filepath.Join(root, "sqlc.yaml")
	raw, err := os.ReadFile(configPath)
	if err != nil {
		t.Fatal(err)
	}
	raw = []byte(strings.ReplaceAll(string(raw), "out: internal/store/sqlc", "out: internal/store/sqlc-alt"))
	if err := os.WriteFile(configPath, raw, 0o644); err != nil {
		t.Fatal(err)
	}
	registry, err := bindConfiguredSQLCBoundary(root, DefaultBackendBoundaryRegistry())
	if err != nil {
		t.Fatal(err)
	}
	rule := findBoundaryRule(t, registry, "store_dependency_surface")
	if boundaryRuleAllowsImport(rule, "internal/store/sqlc") {
		t.Fatal("old unconfigured SQLC output retained store dependency privilege")
	}
	if !boundaryRuleAllowsImport(rule, "internal/store/sqlc-alt") {
		t.Fatal("configured SQLC output did not receive store dependency privilege")
	}
}

func TestConfiguredOrchestratorSQLCOutputRebindsSidecarBoundary(t *testing.T) {
	root := t.TempDir()
	writeCanonicalSQLCGuardFixture(t, root)
	configPath := filepath.Join(root, "cmd", "mcp-orch", "sqlc.yaml")
	raw, err := os.ReadFile(configPath)
	if err != nil {
		t.Fatal(err)
	}
	raw = []byte(strings.ReplaceAll(string(raw), "out: store/sqlc", "out: store/sqlc-alt"))
	if err := os.WriteFile(configPath, raw, 0o644); err != nil {
		t.Fatal(err)
	}
	registry, err := bindConfiguredSQLCBoundary(root, DefaultBackendBoundaryRegistry())
	if err != nil {
		t.Fatal(err)
	}
	rule := findBoundaryRule(t, registry, "mcp_orch_sqlc_sidecar_only")
	if boundaryRuleDeniesImport(rule, "cmd/mcp-orch/store/sqlc") {
		t.Fatal("old unconfigured orchestrator SQLC output retained boundary ownership")
	}
	if !boundaryRuleDeniesImport(rule, "cmd/mcp-orch/store/sqlc-alt") {
		t.Fatal("configured orchestrator SQLC output did not receive sidecar boundary ownership")
	}
}

func TestConfiguredSQLCBoundaryRejectsConsumerWithStaleOutputTopology(t *testing.T) {
	for _, test := range []struct {
		name, config, old, replacement, stale, consumer, importPath string
		ruleID                                                      BoundaryRuleID
	}{
		{"root", "sqlc.yaml", "out: internal/store/sqlc", "out: internal/store/sqlc-alt", "internal/store/sqlc/generated.go", "internal/module/leak.go", "internal/store/sqlc", rootSQLCBoundaryRuleID},
		{"orchestrator", "cmd/mcp-orch/sqlc.yaml", "out: store/sqlc", "out: store/sqlc-alt", "cmd/mcp-orch/store/sqlc/generated.go", "internal/module/leak.go", "cmd/mcp-orch/store/sqlc", orchestratorSQLCBoundaryRuleID},
	} {
		t.Run(test.name, func(t *testing.T) {
			root := t.TempDir()
			writeCanonicalSQLCGuardFixture(t, root)
			configPath := filepath.Join(root, filepath.FromSlash(test.config))
			raw, err := os.ReadFile(configPath)
			if err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(configPath, []byte(strings.Replace(string(raw), test.old, test.replacement, 1)), 0o644); err != nil {
				t.Fatal(err)
			}
			writeSQLCOwnerTestFile(t, root, test.stale, "// Code generated by sqlc. DO NOT EDIT.\npackage sqlc\n")
			consumer := "package module\nimport _ \"github.com/lihah111222333-cloud/super-dolphin-agent/" + test.importPath + "\"\n"
			writeSQLCOwnerTestFile(t, root, test.consumer, consumer)
			_, err = EvaluateBackendBoundaryFile(root, filepath.Join(root, filepath.FromSlash(test.consumer)), test.consumer, DefaultBackendBoundaryRegistry(), test.ruleID)
			if err == nil || !strings.Contains(err.Error(), "stale SQLC output") {
				t.Fatalf("EvaluateBackendBoundaryFile() error = %v, want stale topology rejection", err)
			}
		})
	}
}

func writeSQLCOwnerTestFile(t *testing.T, root, relative, content string) {
	t.Helper()
	absolute := filepath.Join(root, filepath.FromSlash(relative))
	if err := os.MkdirAll(filepath.Dir(absolute), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(absolute, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func findBoundaryRule(t *testing.T, registry BackendBoundaryRegistry, id BoundaryRuleID) BackendBoundaryRule {
	t.Helper()
	for _, rule := range registry.Rules {
		if rule.ID == id {
			return rule
		}
	}
	t.Fatalf("boundary rule %q is missing", id)
	return BackendBoundaryRule{}
}

func boundaryRuleAllowsImport(rule BackendBoundaryRule, importPath string) bool {
	for _, policy := range rule.Allow {
		if policy.ImportPrefix == importPath {
			return true
		}
	}
	return false
}

func boundaryRuleDeniesImport(rule BackendBoundaryRule, importPath string) bool {
	for _, policy := range rule.Deny {
		if policy.ImportPrefix == importPath {
			return true
		}
	}
	return false
}
